import fs from "node:fs";
import path from "node:path";

const sourceDir = path.join("src", "retro-player", "retro");
const outputDir = path.join("extension", "shared");

const DIRECT_SHADER_FILES = [
  "filterPass1LiteShader.ts",
  "filterPass1LiteSimpleShader.ts",
  "filterPass1Pc98LiteShader.ts",
  "filterPass2LiteShader.ts",
  "filterPass2BeamLiteShader.ts",
  "filterPass2BeamLiteKernelShader.ts",
  "filterPass2BeamLiteSimpleShader.ts",
  "filterPass2BeamLiteCompositeShader.ts",
  "filterPass2BeamLiteCrtComposeShader.ts",
  "filterPass2BeamLiteCrtPostShader.ts",
  "filterPass2PhosphorLiteShader.ts",
  "filterPass2PhosphorLiteCoreShader.ts",
  "filterPassCompositeMidShader.ts",
];

const LEGACY_OUTPUTS = [
  "filterShader.js",
  "filterPass1Shader.js",
  "filterPass2Shader.js",
];

const SAMPLING_UNIFORM = "uniform float uSamplingMode;\n";

const SAMPLING_FUNCTIONS = `vec2 targetCellUv(vec2 cell)
{
  return clamp((cell + 0.5) / max(uTargetSize, vec2(1.0)), vec2(0.0), vec2(1.0));
}

vec3 sampleCellAverage4(vec2 cellMin, vec2 cellSize)
{
  vec2 quarter = cellSize * 0.25;
  vec3 sum = vec3(0.0);
  sum += texture(uTexture, clamp(cellMin + vec2(quarter.x, quarter.y), vec2(0.0), vec2(1.0))).rgb;
  sum += texture(uTexture, clamp(cellMin + vec2(cellSize.x - quarter.x, quarter.y), vec2(0.0), vec2(1.0))).rgb;
  sum += texture(uTexture, clamp(cellMin + vec2(quarter.x, cellSize.y - quarter.y), vec2(0.0), vec2(1.0))).rgb;
  sum += texture(uTexture, clamp(cellMin + vec2(cellSize.x - quarter.x, cellSize.y - quarter.y), vec2(0.0), vec2(1.0))).rgb;
  return sum * 0.25;
}

vec3 sampleCellAverage8(vec2 cellMin, vec2 cellSize)
{
  vec3 sum = vec3(0.0);
  sum += texture(uTexture, clamp(cellMin + cellSize * vec2(0.25, 0.25), vec2(0.0), vec2(1.0))).rgb;
  sum += texture(uTexture, clamp(cellMin + cellSize * vec2(0.75, 0.25), vec2(0.0), vec2(1.0))).rgb;
  sum += texture(uTexture, clamp(cellMin + cellSize * vec2(0.25, 0.75), vec2(0.0), vec2(1.0))).rgb;
  sum += texture(uTexture, clamp(cellMin + cellSize * vec2(0.75, 0.75), vec2(0.0), vec2(1.0))).rgb;
  sum += texture(uTexture, clamp(cellMin + cellSize * vec2(0.50, 0.20), vec2(0.0), vec2(1.0))).rgb;
  sum += texture(uTexture, clamp(cellMin + cellSize * vec2(0.50, 0.80), vec2(0.0), vec2(1.0))).rgb;
  sum += texture(uTexture, clamp(cellMin + cellSize * vec2(0.20, 0.50), vec2(0.0), vec2(1.0))).rgb;
  sum += texture(uTexture, clamp(cellMin + cellSize * vec2(0.80, 0.50), vec2(0.0), vec2(1.0))).rgb;
  return sum * 0.125;
}

vec3 sampleCellAverage16(vec2 cellMin, vec2 cellSize)
{
  vec3 sum = vec3(0.0);
  for (int y = 0; y < 4; y++) {
    for (int x = 0; x < 4; x++) {
      vec2 offset = (vec2(float(x), float(y)) + 0.5) / 4.0;
      sum += texture(uTexture, clamp(cellMin + cellSize * offset, vec2(0.0), vec2(1.0))).rgb;
    }
  }
  return sum * (1.0 / 16.0);
}

vec3 sampleBaseSourceColorAtCell(vec2 cell)
{
  vec2 safeTargetSize = max(uTargetSize, vec2(1.0));
  vec2 uv = targetCellUv(cell);
  if (uSamplingMode < 0.5) {
    return texture(uTexture, uv).rgb;
  }

  vec2 clampedCell = clamp(cell, vec2(0.0), safeTargetSize - vec2(1.0));
  vec2 cellMin = clampedCell / safeTargetSize;
  vec2 cellSize = 1.0 / safeTargetSize;
  if (uSamplingMode < 1.5) {
    return sampleCellAverage4(cellMin, cellSize);
  }
  if (uSamplingMode < 2.5) {
    return sampleCellAverage8(cellMin, cellSize);
  }
  return sampleCellAverage8(cellMin, cellSize);
}
`;

const NEAREST_FUNCTIONS = `vec2 targetCellUv(vec2 cell)
{
  return clamp((cell + 0.5) / max(uTargetSize, vec2(1.0)), vec2(0.0), vec2(1.0));
}

vec3 sampleBaseSourceColorAtCell(vec2 cell)
{
  return texture(uTexture, targetCellUv(cell)).rgb;
}
`;

function readSource(fileName) {
  return fs.readFileSync(path.join(sourceDir, fileName), "utf-8");
}

function extractShaderExport(sourcePath, source) {
  const match = source.match(/export const (\w+)\s*=\s*`([\s\S]*?)`;\n?/);
  if (!match) {
    throw new Error(`Could not find shader export in ${sourcePath}`);
  }

  return {
    exportName: match[1],
    shaderSource: match[2],
  };
}

function writeShaderFile(fileName, exportName, shaderSource, sourcePath) {
  const outputPath = path.join(outputDir, fileName.replace(/\.ts$/, ".js"));
  const output = `// Generated by scripts/sync-extension-shader.mjs from ${sourcePath}
export const ${exportName} = \`${shaderSource}\`;
`;
  fs.writeFileSync(outputPath, output);
  console.log(`generated ${outputPath} from ${sourcePath}`);
}

function composeNearestOnlyPass1Shader(source) {
  return source.replace(SAMPLING_UNIFORM, "").replace(SAMPLING_FUNCTIONS, NEAREST_FUNCTIONS);
}

function generatePass1LiteBase() {
  const sourcePath = path.join(sourceDir, "filterPass1LiteBaseShader.ts");
  const baseShaderSource = extractShaderExport(
    path.join(sourceDir, "filterPass1LiteShader.ts"),
    readSource("filterPass1LiteShader.ts"),
  ).shaderSource;
  const removeUniformLine = (source, uniformName) =>
    source.replace(`uniform float ${uniformName};\n`, "");
  const removeBetween = (source, startMarker, endMarker) => {
    const start = source.indexOf(startMarker);
    if (start < 0) return source;
    const end = source.indexOf(endMarker, start);
    if (end < 0) return source;
    return source.slice(0, start) + source.slice(end);
  };

  const withoutCompositeUniforms = [
    "uCompositeEnabled",
    "uCompositeAmount",
    "uCompositeChromaBlur",
    "uCompositeChromaDelay",
    "uCompositeNoise",
  ].reduce((source, uniformName) => removeUniformLine(source, uniformName), baseShaderSource);

  const withoutCompositeFunction = removeBetween(
    withoutCompositeUniforms,
    "vec3 applyCompositeNtsc(vec2 cell, vec3 centerColor)\n",
    "\nvec3 nearestColorAnime(vec3 color)\n",
  );

  const shaderSource = withoutCompositeFunction.replace(
    "  sourceColor = applyCompositeNtsc(cell, sourceColor);\n",
    "",
  );

  writeShaderFile("filterPass1LiteBaseShader.ts", "FILTER_FRAGMENT_PASS1_LITE_BASE", shaderSource, sourcePath);
}

function generatePass1NearestVariants() {
  const simpleSourcePath = path.join(sourceDir, "filterPass1LiteSimpleShader.ts");
  const simpleShaderSource = extractShaderExport(simpleSourcePath, readSource("filterPass1LiteSimpleShader.ts")).shaderSource;
  writeShaderFile(
    "filterPass1LiteNearestShader.ts",
    "FILTER_FRAGMENT_PASS1_LITE_NEAREST",
    composeNearestOnlyPass1Shader(simpleShaderSource),
    path.join(sourceDir, "filterPass1LiteNearestShader.ts"),
  );

  const pc98SourcePath = path.join(sourceDir, "filterPass1Pc98LiteShader.ts");
  const pc98ShaderSource = extractShaderExport(pc98SourcePath, readSource("filterPass1Pc98LiteShader.ts")).shaderSource;
  writeShaderFile(
    "filterPass1Pc98LiteNearestShader.ts",
    "FILTER_FRAGMENT_PASS1_PC98_LITE_NEAREST",
    composeNearestOnlyPass1Shader(pc98ShaderSource),
    path.join(sourceDir, "filterPass1Pc98LiteNearestShader.ts"),
  );
}

function generateBeamCrtKernel() {
  const sourcePath = path.join(sourceDir, "filterPass2BeamLiteCrtKernelShader.ts");
  const kernelSourcePath = path.join(sourceDir, "filterPass2BeamLiteKernelShader.ts");
  const kernelSource = extractShaderExport(kernelSourcePath, readSource("filterPass2BeamLiteKernelShader.ts")).shaderSource;

  const removeUniformLine = (source, uniformName) =>
    source.replace(`uniform float ${uniformName};\n`, "");
  const inlineFloatConstant = (source, uniformName, value) =>
    removeUniformLine(source, uniformName).split(uniformName).join(value.toFixed(4));

  const shaderSource = [
    ["uSamplingMode", 0],
    ["uHorizontalSharpness", 1],
    ["uRgbConvergenceOffset", 0],
    ["uSmoothStrength", 0],
    ["uCurvature", 0.03],
    ["uBeamDarkCutoff", 0.04],
    ["uBeamHorizontalSpread", 1.27],
    ["uBeamWhiteBloom", 1.14],
  ].reduce((source, [uniformName, value]) => inlineFloatConstant(source, uniformName, value), kernelSource);

  writeShaderFile("filterPass2BeamLiteCrtKernelShader.ts", "FILTER_FRAGMENT_PASS2_BEAM_LITE_CRT_KERNEL", shaderSource, sourcePath);
}

fs.mkdirSync(outputDir, { recursive: true });

for (const fileName of DIRECT_SHADER_FILES) {
  const sourcePath = path.join(sourceDir, fileName);
  const source = readSource(fileName);
  const { exportName, shaderSource } = extractShaderExport(sourcePath, source);
  writeShaderFile(fileName, exportName, shaderSource, sourcePath);
}

generatePass1LiteBase();
generatePass1NearestVariants();
generateBeamCrtKernel();

for (const fileName of LEGACY_OUTPUTS) {
  const outputPath = path.join(outputDir, fileName);
  if (!fs.existsSync(outputPath)) {
    continue;
  }

  fs.rmSync(outputPath);
  console.log(`removed legacy ${outputPath}`);
}
